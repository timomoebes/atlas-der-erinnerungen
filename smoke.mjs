import { chromium, webkit } from 'playwright';
const engine = process.env.BROWSER === 'webkit' ? webkit : chromium;   // BROWSER=webkit: closest to iPhone Safari
import { mkdir } from 'node:fs/promises';
const base = 'http://127.0.0.1:4173/';
await mkdir('screenshots', { recursive: true });
const browser = await engine.launch({ headless: true, args: engine === chromium ? ['--use-gl=angle', '--use-angle=swiftshader'] : [] });
const errors = [];
const context = await browser.newContext({ viewport: { width: 1440, height: 900 }, deviceScaleFactor: 1 });
const page = await context.newPage();
page.on('pageerror', error => errors.push(error.message));
page.on('console', msg => { if (msg.type() === 'error') errors.push(msg.text()); });
try {
  await page.goto(base, { waitUntil: 'domcontentloaded' });
  await page.locator('.empty-state').waitFor();
  await page.waitForTimeout(1300);
  await page.screenshot({ path: 'screenshots/desktop-empty.png' });
  console.log('initial', await page.evaluate(() => ({ canvas: !!document.querySelector('canvas'), webglFallback: document.querySelector('#globe').classList.contains('no-webgl'), labels: [...document.querySelectorAll('.place-label')].map(el => ({ text: el.textContent, display: el.style.display, left: el.style.left, top: el.style.top })) })));
  await page.getByRole('button', { name: 'Erinnerung festhalten' }).click();
  await page.locator('[name="title"]').fill('Unser erster Blick aufs Meer');
  await page.locator('[name="date"]').fill('2025-08-12');
  await page.locator('[name="place"]').selectOption('1');
  await page.locator('[name="note"]').fill('Bia, du und ich. Der Himmel war rosa, und das Meer lag plötzlich vor uns.');
  await page.getByRole('button', { name: 'Erinnerung speichern' }).click();
  await page.locator('.memory-detail h3').getByText('Unser erster Blick aufs Meer').waitFor();
  await page.reload();
  await page.locator('.memory-detail h3').getByText('Unser erster Blick aufs Meer').waitFor();
  console.log('persistent', await page.locator('.memory-detail').innerText());
  await page.screenshot({ path: 'screenshots/desktop-memory.png' });
  await page.getByRole('button', { name: 'Ansehen' }).click();
  await page.locator('#presentation').waitFor({ state: 'visible' });
  await page.screenshot({ path: 'screenshots/presentation.png' });
  console.log('presentation', await page.locator('#presentation h2').innerText());
  await page.getByRole('button', { name: 'Präsentation schließen' }).click();
  const downloadPromise = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Sicherung herunterladen' }).click();
  const download = await downloadPromise;
  console.log('export', download.suggestedFilename());
  const backupPath = 'screenshots/roundtrip.json';
  await download.saveAs(backupPath);
  const backup = JSON.parse(await (await import('node:fs/promises')).readFile(backupPath, 'utf8'));
  if (backup.moments.length !== 1 || backup.moments[0].title !== 'Unser erster Blick aufs Meer') throw new Error('Export data mismatch');
  await page.getByRole('button', { name: 'Erinnerung bearbeiten' }).click();
  await page.locator('[name="title"]').fill('Angekommen am Meer');
  await page.locator('#photo-input').setInputFiles('screenshots/desktop-empty.png');
  await page.locator('#photo-preview img').waitFor();
  await page.getByRole('button', { name: 'Erinnerung speichern' }).click();
  await page.locator('.memory-detail h3').getByText('Angekommen am Meer').waitFor();
  if (await page.locator('.memory-photo').count() !== 1) throw new Error('Photo not saved');
  page.once('dialog', dialog => dialog.accept());
  await page.locator('#import-file').setInputFiles(backupPath);
  await page.locator('.memory-detail h3').getByText('Unser erster Blick aufs Meer').waitFor();
  if (await page.locator('.memory-photo').count() !== 0) throw new Error('Import did not replace photo');
  console.log('roundtrip', 'edit/photo/import passed');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: 'screenshots/mobile-memory.png', fullPage: true });
  console.log('mobile', await page.evaluate(() => ({ scrollWidth: document.documentElement.scrollWidth, innerWidth, globe: document.querySelector('.visual').getBoundingClientRect().toJSON() })));
  console.log('errors', errors);
  if (errors.length) process.exitCode = 1;
} finally { await browser.close(); }
